const PEX_STOP=new Set(['team','teams','databricks','customer','customers','account','accounts','genie','the','our','their','poc','ai','ml','dbx','ms','na','tbd','none','partner','partners','use','case','cases','next','steps','sfdc','uc','data','and','with','for','to','is','are']);
// Trailing words that describe the work, not the brand: "KPMG Project" -> "KPMG".
const PEX_GENERIC=new Set(['project','projects','implementation','involved','engaged','team','teams']);
const PEX_PATTERNS=[
  /\bpartner[:\-\s]+([A-Z][A-Za-z0-9&.\s]{2,40})/g,
  /\bwith\s+partner\s+([A-Z][A-Za-z0-9&.\s]{2,40})/g,
  /\b(?:SI|systems?\s+integrator)[:\-\s]+([A-Z][A-Za-z0-9&.\s]{2,40})/g,
  /\bonboard(?:ing)?\s+([A-Z][A-Za-z0-9&.\s]{2,40}?)\s+as\s+(?:a|the|our)\s+partner\b/g,
  /\b([A-Z][A-Za-z0-9&.\s]{2,40}?)\s+as\s+(?:a|the|our)\s+partner\b/g];
// Keep only the leading run of proper-noun tokens — the brand, not the sentence.
function pexProper(cap){
  const toks=(cap||'').replace(/[*_`]/g,'').trim().split(/\s+/);const out=[];
  for(const t of toks){const c=t.replace(/^[("'\[]+/,'').replace(/[.,;:)\]("']+$/,'');
    if(!c)break;if(/^[A-Z]/.test(c)||c==='&')out.push(c);else break;}
  while(out.length>1&&PEX_GENERIC.has(out[out.length-1].toLowerCase()))out.pop();
  return out.join(' ').replace(/\s*&\s*$/,'').trim();}
const pexNorm=name=>name.toLowerCase().replace(/[^a-z0-9]/g,'');
function pexValid(name){
  if(!name)return false;const w=name.split(/\s+/);
  if(w.length>4||name.length<3||name.length>40)return false;
  if(!/^[A-Z]/.test(name)||!/[A-Za-z]/.test(name))return false;
  if(w.every(x=>PEX_STOP.has(x.toLowerCase())))return false;
  return true;}
function pexExtract(text){
  if(!text)return [];const found=[];const seen=new Set();
  for(const re of PEX_PATTERNS){for(const m of String(text).matchAll(re)){
    const name=pexProper(m[1]);if(!pexValid(name))continue;
    const key=name.toLowerCase();const idx=m.index||0;
    const start=Math.max(0,text.lastIndexOf('\n',idx-1)+1);
    let end=text.indexOf('\n',idx);if(end<0)end=text.length;
    const line=text.slice(start,end).trim();const dk=key+'|'+line;
    if(seen.has(dk))continue;seen.add(dk);found.push({partner:name,key,excerpt:line});}}
  return found;}
