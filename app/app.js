/* Which flag rules count toward the SCORE. `state` alone is not enough: advisory
   forecast flags (cq-review / cq1-understaged / u1-forecast-cq) run the same
   grace→scored lifecycle as real defects and so carry state==='scored', yet the
   score never counts them (engine scoring.mjs filters isFixRule first). The engine
   now stamps each issue with `isFix`; we prefer it and fall back to the rule set so
   this view is correct even on a snapshot written before that field existed. */
var HYG_ADVISORY_RULES={'cq-review':1,'cq1-understaged':1,'u1-forecast-cq':1};
function hygIsFix(i){return i.isFix!=null?!!i.isFix:!HYG_ADVISORY_RULES[i.ruleType];}
/* The bucket a single flag-row belongs to — the SAME split the score makes:
   'scored' = a live defect that is dragging the number down; 'headsup' = a defect
   still in grace OR an advisory recommendation (never scored); 'waived' = excluded.
   Unknown states fall to 'headsup', never 'scored', so a stray value can never again
   silently inflate "to fix". */
function hygBucket(i){
  if(i.state==='waived')return 'waived';
  if(hygIsFix(i)&&i.state==='scored')return 'scored';
  return 'headsup';}

/* Roll every flag up to one verdict per ITEM, with the score's own precedence:
   scored beats heads-up beats waived. An item with one live defect and one flag
   still in grace is a live problem; counting it under "not yet scored" too would
   make the tiles add to more items than the list below shows. This now mirrors the
   score exactly — an item counts as "to fix" only when it has a live FIX-rule flag,
   so the Territory/AE "N to fix" badge equals the "clean" count on the scorecard. */
function hygItemVerdicts(list){const rank={waived:0,headsup:1,scored:2},best={};
  list.forEach(i=>{const k=i.ownerId+'|'+(i.itemKey||i.account+':'+(i.ucoName||i.oppName));
    const r=rank[hygBucket(i)];if(best[k]==null||r>best[k])best[k]=r;});
  const out={scored:0,headsup:0,waived:0};
  Object.keys(best).forEach(k=>{out[best[k]===2?'scored':best[k]===1?'headsup':'waived']++;});
  return out;}

