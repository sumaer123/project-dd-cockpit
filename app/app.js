function mergeWeekly(scopeDict,week){
  // scopeDict: {wid:{newOpps,newUCs,progressed}} -> merged for week or all
  const out={newOpps:[],newUCs:[],progressed:[]};
  Object.entries(scopeDict||{}).forEach(([wid,slot])=>{
    if(week!=='all'&&wid!==week)return;
    out.newOpps.push(...(slot.newOpps||[]));out.newUCs.push(...(slot.newUCs||[]));out.progressed.push(...(slot.progressed||[]));});
  if(week==='all'&&out.progressed.length){
    // collapse a UC that moved in multiple weeks into ONE net move (avoid $ double-count)
    const ord={U1:1,U2:2,U3:3,U4:4,U5:5,U6:6},m={};
    out.progressed.forEach(p=>{const k=(p.accountId||'')+'|'+p.name,e=m[k];
      if(!e){m[k]={...p};}
      else{if(ord[p.to]>ord[e.to]){e.to=p.to;e.live=p.live;}if(ord[p.from]<ord[e.from])e.from=p.from;}});
    out.progressed=Object.values(m);}
  return out;}
