/* ---------- Top Gaining Accounts (T7D / T28D run-rate momentum) ---------- */
// Grounded in the data model: account.weekly[i] = avg daily run-rate ($/day) for
// week i (oldest→newest). t7d = weekly[last]; t28d = mean(weekly[last-3..last]).
// "Gain" = the current window's run-rate minus the immediately-prior equal-length
// window's run-rate, in $/day. Positive = accelerating consumption (a gainer).
function gainOf(a,win){
  const w=a&&a.weekly; if(!Array.isArray(w))return null; const n=w.length;
  const mean=arr=>arr.reduce((s,x)=>s+(x||0),0)/(arr.length||1);
  let cur,prev;
  if(win==='t7d'){ if(n<2)return null; cur=w[n-1]; prev=w[n-2]; }
  else if(win==='t90'){ if(n<26)return null; cur=mean(w.slice(n-13)); prev=mean(w.slice(n-26,n-13)); }
  else { if(n<8)return null; cur=mean(w.slice(n-4)); prev=mean(w.slice(n-8,n-4)); }
  return {cur,prev,gain:cur-prev,pct:prev>0?(cur-prev)/prev*100:null};
}
function getTopGainingAccounts(accts,win,limit){
  limit=limit||5;
  return (accts||[]).map(a=>{const g=gainOf(a,win);return g?Object.assign({a},g):null;})
    .filter(x=>x&&x.gain>0)
    .sort((x,y)=>y.gain-x.gain)
    .slice(0,limit);
}
